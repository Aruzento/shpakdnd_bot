UNITS = ('Медная монета', 'Серебряная монета', 'Золотая монета')
SOURCE_MONEY_KEYS = frozenset(name.casefold() for name in MASTER_MONEY)


def is_source_money(name):
    return name.strip().casefold() in SOURCE_MONEY_KEYS
